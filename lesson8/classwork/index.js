// Пример 6: Комплексный объект и перебор свойств с помощью цикла for...in
// В этом примере показано:
// 1. Объект user со свойствами разных типов, включая массив (hobbies).
// 2. Получение, изменение, добавление и удаление свойств объекта.
// 3. Итерация по всем ключам (свойствам) объекта с помощью цикла for...in и
//    вывод пар ключ-значение через шаблонную строку `${item}: ${user[item]}`.
// ==============================================================================

const user = {
    isStudent: true,
    hobbies: ["capybara", "capybara", "capybara"],
    city: "Zaporozhye",
    age: 20,
    name: "Capybara"
};

console.log(user.name, user.city);

user.age = 21;
console.log(user.age);

user.email = "wonkru-dev@proton.me";
console.log(user.email);

delete user.city;
console.log(user);

for (const item in user) console.log(`${item}: ${user[item]}`);
